export function translate(language: Language, key: MessageKey, ...values: (string | number)[]): string {
  const text = language === "en" ? english[key] : chinese[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (placeholder, index) => String(values[Number(index)] ?? placeholder));
}

export function translateDetail(language: Language, detail: string): string {
  const key = detail.trim();
  return Object.prototype.hasOwnProperty.call(english, key) ? translate(language, key as MessageKey) : detail;
}
